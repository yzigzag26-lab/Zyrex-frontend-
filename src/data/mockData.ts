/** Simple frontend intent matcher — replaces any real model routing. */
export function findMockResponse(prompt: string): MockAiResponse {
  const p = prompt.toLowerCase();
  let best: { response: MockAiResponse; score: number } | null = null;
  for (const response of mockAiResponses) {
    let score = 0;
    for (const keyword of response.keywords) {
      if (p.includes(keyword)) score += keyword.length;
    }
    if (score > 0 && (!best || score > best.score)) best = { response, score };
  }
  return best ? best.response : fallbackResponse;
}

