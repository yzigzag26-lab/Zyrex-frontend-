/** Deterministic pseudo-random sparkline used for evidence placeholders. */
function spark(seed: number, len = 26, drift = 0.15): number[] {
  const out: number[] = [];
  let x = seed * 9301 + 49297;
  let value = 40;
  for (let i = 0; i < len; i++) {
    x = (x * 9301 + 49297) % 233280;
    const noise = (x / 233280 - 0.5) * 16;
    value = Math.max(6, Math.min(94, value + drift + noise));
    out.push(Math.round(value));
  }
  return out;
}

function evidence(before: string, during: string, after: string, seed: number): EvidenceShot[] {
  return [
    {
      label: "Before",
      caption: before,
      capturedAt: "pre-entry",
      present: true,
      preview: spark(seed),
    },
    {
      label: "During",
      caption: during,
      capturedAt: "in-position",
      present: seed % 3 !== 1,
      preview: spark(seed + 7, 26, 0.05),
    },
    {
      label: "After",
      caption: after,
      capturedAt: "post-exit",
      present: true,
      preview: spark(seed + 13, 26, -0.1),
    },
  ];
}

